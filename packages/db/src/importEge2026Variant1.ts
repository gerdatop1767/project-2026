/** Rough part classification for the report only — Part 1 = 1-12, Part 2 = 13-19; not stored as its own column since it's a deterministic function of taskNumber for this subject. */
export function partForTaskNumber(taskNumber: number): 1 | 2 {
  return taskNumber <= 12 ? 1 : 2;
}

/**
 * Difficulty follows the exam's own documented Part 1 / Part 2 split
 * (Part 1 = базовый/повышенный, Part 2 = высокий), not a per-task
 * subjective judgement call we have no reliable way to make yet.
 */
function difficultyForTaskNumber(taskNumber: number): 1 | 2 | 3 {
  return partForTaskNumber(taskNumber) === 1 ? 2 : 3;
}

function normalizeForHash(text: string): string {
  return text.trim().toLowerCase().replace(/\s+/g, ' ');
}

function contentHashFor(subjectId: string, taskNumber: number, statement: string): string {
  return createHash('sha256')
    .update(`${subjectId}|${taskNumber}|${normalizeForHash(statement)}`)
    .digest('hex');
}

export async function importVariant1(db: Database) {
  await db
    .insert(schema.subjects)
    .values({ id: 'math', name: 'Математика' })
    .onConflictDoUpdate({ target: schema.subjects.id, set: { name: 'Математика' } });

  const topicIdBySlug = new Map<string, string>();
  for (const slug of new Set(importTasks.map((t) => t.topicSlug))) {
    const topicName = importTasks.find((t) => t.topicSlug === slug)!.topicName;
    const [topic] = await db
      .insert(schema.topics)
      .values({ subjectId: 'math', slug, name: topicName })
      .onConflictDoUpdate({
        target: [schema.topics.subjectId, schema.topics.slug],
        set: { name: topicName },
      })
      .returning();
    topicIdBySlug.set(slug, topic!.id);
  }

  const [collection] = await db
    .insert(schema.collections)
    .values({
      subjectId: 'math',
      slug: COLLECTION_SLUG,
      title: COLLECTION_TITLE,
      publisher: COLLECTION_PUBLISHER,
      year: SOURCE_YEAR,
      status: 'published',
      examFormat: EXAM_FORMAT,
    })
    .onConflictDoUpdate({
      target: schema.collections.slug,
      set: {
        title: COLLECTION_TITLE,
        publisher: COLLECTION_PUBLISHER,
        year: SOURCE_YEAR,
        examFormat: EXAM_FORMAT,
      },
    })
    .returning();

  const [variant] = await db
    .insert(schema.variants)
    .values({
      collectionId: collection!.id,
      variantNumber: VARIANT,
      title: VARIANT_TITLE,
      year: SOURCE_YEAR,
      status: 'published',
      sourceFile: SOURCE_FILE,
      sourcePageStart: SOURCE_PAGE_START,
      sourcePageEnd: SOURCE_PAGE_END,
    })
    .onConflictDoUpdate({
      target: [schema.variants.collectionId, schema.variants.variantNumber],
      set: {
        title: VARIANT_TITLE,
        sourceFile: SOURCE_FILE,
        sourcePageStart: SOURCE_PAGE_START,
        sourcePageEnd: SOURCE_PAGE_END,
        updatedAt: new Date(),
      },
    })
    .returning();

  // Content sync, not a reseed: this task's row (found by its stable
  // identity — subject + source + variant + task number, never by a
  // freshly-generated id) already exists once a variant has been
  // imported anywhere, including production. Deleting and reinserting
  // here would mint a new `tasks.id` every run, which orphans that
  // task's `attempts`/`mistakes` (hard FK failure the moment a real
  // user has answered it) and silently breaks bookmarks/links even
  // when no attempts exist yet — exactly how production ended up stuck
  // showing the plain-text content from its first-ever import while
  // this file kept gaining real LaTeX, `correctAnswerDisplay`, and
  // fidelity fixes underneath it (EGE Fidelity: Final Polish, content
  // migration). UPDATE-in-place keeps `id` (and therefore every FK
  // pointing at it) untouched; only a task number genuinely new to
  // this variant gets INSERTed.
  const existingRows = await db
    .select({ id: schema.tasks.id, taskNumber: schema.tasks.taskNumber })
    .from(schema.tasks)
    .where(
      and(
        eq(schema.tasks.subjectId, 'math'),
        eq(schema.tasks.source, SOURCE),
        eq(schema.tasks.sourceVariant, VARIANT),
      ),
    );
  const existingIdByNumber = new Map(existingRows.map((r) => [r.taskNumber, r.id]));

  const taskIds: string[] = [];
  for (const t of importTasks) {
    const values = {
      subjectId: 'math',
      taskNumber: t.taskNumber,
      topicId: topicIdBySlug.get(t.topicSlug),
      difficulty: difficultyForTaskNumber(t.taskNumber),
      conditionMd: t.conditionMd,
      imageUrl: t.imageUrl,
      answerType: t.answerType ?? ('short_answer' as const),
      correctAnswer: t.correctAnswer,
      correctAnswerDisplay: t.correctAnswerDisplay ?? null,
      explanationMd: t.explanationMd,
      hintMd: t.hintMd,
      solutionSteps: t.solutionSteps,
      source: SOURCE,
      sourceUrl: null,
      sourceYear: SOURCE_YEAR,
      sourceDocument: SOURCE_DOCUMENT,
      sourceVariant: VARIANT,
      sourcePage: t.sourcePage,
      rawStatement: t.rawStatement,
      contentHash: contentHashFor('math', t.taskNumber, t.rawStatement),
      tags: [IMPORT_TAG],
      status: t.status,
    };

    const existingId = existingIdByNumber.get(t.taskNumber);
    if (existingId) {
      await db
        .update(schema.tasks)
        .set({ ...values, updatedAt: new Date() })
        .where(eq(schema.tasks.id, existingId));
      taskIds.push(existingId);
    } else {
      const [row] = await db.insert(schema.tasks).values(values).returning({ id: schema.tasks.id });
      taskIds.push(row!.id);
    }
  }

  // position = taskNumber: this variant's full-exam order is exactly
  // the official question numbering, 1-19 with no gaps. Upsert by the
  // (variantId, taskId) unique index rather than delete-then-insert —
  // task ids are now stable across re-imports, so this membership can
  // be too.
  for (let i = 0; i < importTasks.length; i++) {
    await db
      .insert(schema.variantTasks)
      .values({ variantId: variant!.id, taskId: taskIds[i]!, position: importTasks[i]!.taskNumber })
      .onConflictDoUpdate({
        target: [schema.variantTasks.variantId, schema.variantTasks.taskId],
        set: { position: importTasks[i]!.taskNumber },
      });
  }

  return {
    total: importTasks.length,
    published: importTasks.filter((t) => t.status === 'published').length,
    needsReview: importTasks.filter((t) => t.status === 'needs_review').length,
    collectionId: collection!.id,
    variantId: variant!.id,
  };
}

async function main() {
  const databaseUrl = process.env.DATABASE_URL;
  if (!databaseUrl) {
    throw new Error('DATABASE_URL is not set');
  }
  const client = postgres(databaseUrl, { max: 1 });
  try {
    const db = drizzle(client, { schema });
    const result = await importVariant1(db);
    console.log(
      `Imported ${result.total} tasks from Вариант 1 (${result.published} published, ${result.needsReview} needs_review).`,
    );
  } finally {
    await client.end();
  }
}

if (isMainModule(import.meta.url)) {
  main().catch((error: unknown) => {
    console.error(error);
    process.exit(1);
  });
}
