const words = (s: string) => new Set(s.toLowerCase().match(/[а-яё]+/g) ?? []);
/** Twins: a correct sentence and a wrong one built on the same words. */
function twins(a: string, b: string): boolean {
  const x = words(a);
  const y = words(b);
  const common = [...x].filter((w) => y.has(w)).length;
  return common / Math.min(x.size, y.size) >= 0.5;
}

export function generateSyntaxTasks(count = 100, seed = 8082027, maxUses = 6): BankTask[] {
  const rand = rng(seed);
  const uses = new Map<string, number>();
  const seen = new Set<string>();
  const typeNames = Object.keys(TYPES);
  const drafts: { errors: E[]; correct: C[]; order: string[]; score: number }[] = [];
  let guard = 0;
  while (drafts.length < count) {
    if (++guard > count * 300) throw new Error('task 8: cannot build enough tasks');
    const types = shuffle(typeNames, rand).slice(0, 5);
    const errors: E[] = [];
    for (const ty of types) {
      const cand = shuffle(
        ERRORS.filter((e) => e[0] === ty && (uses.get(e[1]) ?? 0) < maxUses),
        rand,
      ).sort((a, b) => (uses.get(a[1]) ?? 0) - (uses.get(b[1]) ?? 0));
      if (cand[0]) errors.push(cand[0]);
    }
    if (errors.length !== 5) continue;
    const correct: C[] = [];
    for (const c of shuffle(CORRECT, rand).sort(
      (a, b) => (uses.get(a[0]) ?? 0) - (uses.get(b[0]) ?? 0),
    )) {
      if (correct.length === 4) break;
      if ((uses.get(c[0]) ?? 0) >= maxUses + 3) continue;
      if (errors.some((e) => twins(e[1], c[0])) || correct.some((x) => twins(x[0], c[0]))) continue;
      correct.push(c);
    }
    if (correct.length !== 4) continue;
    const key = [...errors.map((e) => e[1]), ...correct.map((c) => c[0])].sort().join('|');
    if (seen.has(key)) continue;
    seen.add(key);
    for (const s of [...errors.map((e) => e[1]), ...correct.map((c) => c[0])])
      uses.set(s, (uses.get(s) ?? 0) + 1);
    const order = shuffle([...errors.map((e) => e[1]), ...correct.map((c) => c[0])], rand);
    const score = errors.filter((e) => TYPES[e[0]]!.hard).length + rand() * 0.01;
    drafts.push({ errors, correct, order, score });
  }
  const rank = drafts.map((d, i) => ({ i, s: d.score })).sort((a, b) => a.s - b.s);
  const diff = new Map<number, Difficulty>();
  rank.forEach((o, r) => diff.set(o.i, r < count * 0.3 ? 1 : r < count * 0.7 ? 2 : 3));
  return drafts.map((d, i) => {
    const okNums = d.correct
      .map((c) => ({ n: d.order.indexOf(c[0]) + 1, why: c[1] }))
      .sort((a, b) => a.n - b.n);
    return buildMatchTask({
      taskNumber: 8,
      n: i + 1,
      difficulty: diff.get(i)!,
      kind: d.errors.some((e) => e[0] === 'spp' || e[0] === 'kosv')
        ? 'сложные предложения и косвенная речь'
        : d.errors.some((e) => e[0] === 'dee' || e[0] === 'prich')
          ? 'обороты'
          : 'согласование и управление',
      instruction:
        'Установите соответствие между грамматическими ошибками и предложениями, в которых они допущены: к каждой позиции первого столбца подберите соответствующую позицию из второго столбца.',
      leftTitle: 'ГРАММАТИЧЕСКИЕ ОШИБКИ',
      left: d.errors.map((e) => TYPES[e[0]]!.label),
      rightTitle: 'ПРЕДЛОЖЕНИЯ',
      right: d.order,
      answer: d.errors.map((e) => d.order.indexOf(e[1])),
      intro:
        'Для каждой ошибки из первого столбца ищем предложение, где она допущена. Четыре предложения построены правильно — они в ответ не входят.',
      why: d.errors.map((e) => e[2]),
      tip: `Предложения ${okNums.map((x) => x.n).join(', ')} построены правильно: ${okNums
        .map((x) => `(${x.n}) ${x.why}`)
        .join('; ')}.`,
      hint: 'Начни с ошибок, которые видно сразу: падеж после «благодаря, согласно, вопреки», согласование причастия, деепричастный оборот при безличном сказуемом, название в кавычках.',
    });
  });
}

