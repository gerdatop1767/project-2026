export function generateCommaTasks(count = 100, seed = 16162027, maxUses = 5): BankTask[] {
  const rand = rng(seed);
  const uses = new Map<string, number>();
  const seen = new Set<string>();
  const drafts: { units: U[]; score: number }[] = [];
  let guard = 0;
  while (drafts.length < count) {
    if (++guard > count * 300) throw new Error('task 16: cannot build enough tasks');
    const want = [1, 2, 2, 3, 3, 4][Math.floor(rand() * 6)]!;
    const pool = shuffle(UNITS, rand)
      .filter((u) => (uses.get(u[1]) ?? 0) < maxUses)
      .sort((a, b) => (uses.get(a[1]) ?? 0) - (uses.get(b[1]) ?? 0));
    const yes = pool.filter((u) => commasOf(u[1]) === 1).slice(0, want);
    const no = pool.filter((u) => commasOf(u[1]) !== 1).slice(0, 5 - want);
    if (yes.length !== want || no.length !== 5 - want) continue;
    const units = shuffle([...yes, ...no], rand);
    const key = units
      .map((u) => u[1])
      .sort()
      .join('|');
    if (seen.has(key)) continue;
    seen.add(key);
    for (const u of units) uses.set(u[1], (uses.get(u[1]) ?? 0) + 1);
    drafts.push({ units, score: units.reduce((s, u) => s + u[0], 0) + rand() * 0.01 });
  }
  const order = drafts.map((d, i) => ({ i, s: d.score })).sort((a, b) => a.s - b.s);
  const diff = new Map<number, Difficulty>();
  order.forEach((o, rank) => diff.set(o.i, rank < count * 0.3 ? 1 : rank < count * 0.7 ? 2 : 3));
  return drafts.map((d, i) => buildCommaTask(i + 1, d.units, diff.get(i)!));
}

