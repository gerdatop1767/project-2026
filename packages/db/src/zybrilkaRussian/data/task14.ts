const HOW: Record<How, string> = { s: 'слитно', r: 'раздельно', d: 'через дефис' };
const ASK: Record<How, string> = { s: '**СЛИТНО**', r: '**РАЗДЕЛЬНО**', d: '**ЧЕРЕЗ ДЕФИС**' };
const ITEM = /\{([^}:]+):([srd])\}/g;

function items(s: string): { raw: string; how: How }[] {
  return [...s.matchAll(ITEM)].map((m) => ({ raw: m[1]!, how: m[2] as How }));
}
/** `(по)французски` → (**ПО**)**ФРАНЦУЗСКИ**. */
const render = (s: string) =>
  s.replace(ITEM, (_, raw: string) =>
    raw.replace(
      /\(([^)]+)\)|([^()]+)/g,
      (__, inParens: string | undefined, rest: string | undefined) =>
        inParens ? `(**${inParens.toUpperCase()}**)` : `**${rest!.toUpperCase()}**`,
    ),
  );
function written(raw: string, how: How, atStart: boolean): string {
  const parts = raw.split(/[()]/).filter(Boolean);
  const w = parts.join(how === 's' ? '' : how === 'r' ? ' ' : '-');
  return atStart ? w : w.charAt(0).toLowerCase() + w.slice(1);
}

export function buildHyphenTask(n: number, units: readonly U[], ask: How, d: Difficulty): BankTask {
  const flags = units.map((u) => items(u[2]).every((it) => it.how === ask));
  const digits = digitsOf(flags);
  const kinds = new Set(units.map((u) => u[1]));
  return {
    taskNumber: 14,
    n,
    difficulty: d,
    kind: `спрашивают «${HOW[ask]}»`,
    conditionMd: [
      `Укажите варианты ответов, в которых все выделенные слова пишутся ${ASK[ask]}. Запишите номера ответов.`,
      ...units.map((u, i) => `${i + 1}) ${render(u[2])}`),
    ].join('\n\n'),
    answer: { type: 'digits', digits },
    explanationMd: [
      `Определяем, чем является каждое выделенное сочетание (наречием, служебным словом, сложным словом, местоимением с частицей), и пишем его по правилу. Нужны предложения, где **оба** слова пишутся ${HOW[ask]}.`,
      ...units.map((u, i) => {
        const its = items(u[2]);
        const parts = its.map((it, k) => {
          const atStart = u[2].trimStart().startsWith(`{${it.raw}:`);
          return `**${written(it.raw, it.how, atStart)}** — ${u[3 + k]}`;
        });
        return `${i + 1}) ${parts.join('; ')}.${flags[i] ? ' Оба слова пишутся ' + HOW[ask] + ' — подходит.' : ''}`;
      }),
      `**Обрати внимание.** ${
        kinds.has('служ')
          ? 'Союзы и предлоги (тоже, также, чтобы, зато, поэтому, вследствие, ввиду, насчёт) пишутся слитно, а их «двойники» — раздельно: это местоимение с частицей или предлог с существительным. Проверь заменой: «тоже» = «и», «то же» = «то же самое»; «вследствие» = «из-за», «в следствии» = «в расследовании».'
          : kinds.has('слож')
            ? 'Сложные прилагательные из равноправных частей и оттенки цвета пишутся через дефис (русско-английский, тёмно-синий), из подчинительного сочетания — слитно (железнодорожный). Пол- пишется через дефис перед гласной, «л» и прописной буквой, иначе слитно; полу- — всегда слитно.'
            : 'Наречия с по- и суффиксами -ски, -ому, -ему пишутся через дефис (по-русски, по-новому), частицы -то, -либо, -нибудь, -ка, -таки и приставка кое- — тоже. Сочетания предлога с существительным (на ходу, в обнимку, без оглядки) пишутся раздельно.'
      }`,
      `Ответ: ${digits}.`,
    ].join('\n\n'),
    hintMd:
      'Определи часть речи сочетания. Задай вопрос: если можно вставить слово между частями или поставить вопрос к существительному («на какую встречу?»), пишется раздельно.',
  };
}

export function generateHyphenTasks(count = 100, seed = 14142027, maxUses = 6): BankTask[] {
  const rand = rng(seed);
  const uses = new Map<string, number>();
  const seen = new Set<string>();
  const both = (u: U, h: How) => items(u[2]).every((it) => it.how === h);
  const drafts: { units: U[]; ask: How; score: number }[] = [];
  let guard = 0;
  while (drafts.length < count) {
    if (++guard > count * 300) throw new Error('task 14: cannot build enough tasks');
    const ask = (['s', 'r', 'd'] as const)[drafts.length % 3]!;
    const want = [1, 2, 2, 2, 3, 3][Math.floor(rand() * 6)]!;
    const pool = shuffle(UNITS, rand)
      .filter((u) => (uses.get(u[2]) ?? 0) < maxUses)
      .sort((a, b) => (uses.get(a[2]) ?? 0) - (uses.get(b[2]) ?? 0));
    const yes = pool.filter((u) => both(u, ask)).slice(0, want);
    const no = pool.filter((u) => !both(u, ask)).slice(0, 5 - want);
    if (yes.length !== want || no.length !== 5 - want) continue;
    const units = shuffle([...yes, ...no], rand);
    const key =
      units
        .map((u) => u[2])
        .sort()
        .join('|') + ask;
    if (seen.has(key)) continue;
    seen.add(key);
    for (const u of units) uses.set(u[2], (uses.get(u[2]) ?? 0) + 1);
    drafts.push({ units, ask, score: units.reduce((s, u) => s + u[0], 0) + rand() * 0.01 });
  }
  const order = drafts.map((d, i) => ({ i, s: d.score })).sort((a, b) => a.s - b.s);
  const diff = new Map<number, Difficulty>();
  order.forEach((o, rank) => diff.set(o.i, rank < count * 0.3 ? 1 : rank < count * 0.7 ? 2 : 3));
  return drafts.map((d, i) => buildHyphenTask(i + 1, d.units, d.ask, diff.get(i)!));
}

