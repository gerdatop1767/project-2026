/**
 * «Правила игры» — what each mini-game asks, how to answer, how points are
 * counted and when a round ends. Written for a student, per game: no two
 * games share one generic text (a test checks that).
 */
export interface MiniGameRules {
  /** What the game trains, in one sentence. */
  readonly goal: string;
  /** How a question looks and how to answer it. */
  readonly how: readonly string[];
  /** How the round's result is counted. */
  readonly scoring: string;
  /** When the round ends and what happens to mistakes. */
  readonly end: string;
}

