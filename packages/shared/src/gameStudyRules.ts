/**
 * «Правила» in the mini-games: the study material of the ЕГЭ task a game
 * trains — not how to play it (that is `miniGameRules`, «Как играть»).
 * Every rule has the same seven parts, so a student always finds the same
 * thing in the same place: the rule's name, when it applies, its cases
 * (with tables where a table says it better), exceptions, examples,
 * typical mistakes and a short memo.
 *
 * Inline `**…**` marks the letter or word that matters; nothing else is
 * markup. The texts follow the school rules as ЕГЭ checks them (the
 * project's own theory, content/theory/, says the same in longer form).
 */
export interface StudyTable {
  readonly head: readonly string[];
  readonly rows: readonly (readonly string[])[];
}

export interface StudyCase {
  readonly title: string;
  readonly text?: string;
  readonly points?: readonly string[];
  readonly table?: StudyTable;
}

export interface StudyRule {
  /** 1. Название правила. */
  readonly title: string;
  readonly egeTask: string;
  /** 2. Когда применяется. */
  readonly when: string;
  /** 3. Основные случаи. */
  readonly cases: readonly StudyCase[];
  /** 4. Исключения. */
  readonly exceptions: readonly string[];
  /** 5. Примеры. */
  readonly examples: readonly { readonly text: string; readonly note: string }[];
  /** 6. Типичные ошибки. */
  readonly mistakes: readonly {
    readonly wrong: string;
    readonly right: string;
    readonly why: string;
  }[];
  /** 7. Краткая памятка. */
  readonly memo: readonly string[];
}

