/**
 * «Словарные слова и исключения» (docs/DICTIONARY_GAME.md): the words a
 * student has to KNOW for the orthography tasks of ЕГЭ — dictionary words,
 * exceptions and hard spellings — grouped by task and category.
 *
 * Every word has: the right spelling, the same word with the orthogram as
 * a gap («р..сток»), the right letter(s) and the wrong one(s), the rule
 * (the category's, or the word's own note) and, for hard words, a memory
 * aid. A memory aid is a trick to remember the spelling — NEVER presented
 * as the word's history (etymology), and the screen says so.
 *
 * Words are listed in their dictionary spelling (Орфографический словарь
 * РАН); tests check that every gap, filled with its answer, gives the
 * word, and that no two entries are the same word.
 */
export type DictAnswerKind = 'letter' | 'spelling';

export interface DictWord {
  /** Stable id inside the game: `${task}:${category}:${word}`. */
  readonly key: string;
  readonly word: string;
  /** The word with its orthogram as «..» (letters) or «(НЕ)ВЕЖДА» (spelling). */
  readonly gap: string;
  readonly answer: string;
  /** Every choice, the answer included. */
  readonly options: readonly string[];
  readonly exception: boolean;
  /** Why this spelling: the word's own note, else the category's rule. */
  readonly explanation: string;
  /** A memory aid (association, short story, a split, a comparison). */
  readonly memo?: string;
}

export interface DictCategory {
  readonly id: string;
  readonly title: string;
  /** The rule of the category, short. */
  readonly rule: string;
  readonly kind: DictAnswerKind;
  readonly words: readonly DictWord[];
}

export interface DictTask {
  readonly taskNumber: number;
  readonly title: string;
  readonly description: string;
  readonly categories: readonly DictCategory[];
}

interface Raw {
  gap: string;
  answer: string;
  alt: string;
  exception?: boolean;
  note?: string;
  memo?: string;
}

/** `'р..сток|о|а|!|note|memo'`: gap, answer, wrong letter, «!» = exception. */
function parse(line: string): Raw {
  const [gap, answer, alt, flag, note, memo] = line.split('|');
  return {
    gap: gap!,
    answer: answer!,
    alt: alt!,
    exception: flag === '!',
    note: note || undefined,
    memo: memo || undefined,
  };
}

function letters(
  task: number,
  id: string,
  title: string,
  rule: string,
  lines: readonly string[],
): DictCategory {
  return {
    id,
    title,
    rule,
    kind: 'letter',
    words: lines.map((line) => {
      const r = parse(line);
      const word = r.gap.replace('..', r.answer);
      return {
        key: `${task}:${id}:${word}`,
        word,
        gap: r.gap,
        answer: r.answer,
        options: [r.answer, r.alt].sort((a, b) => a.localeCompare(b, 'ru')),
        exception: r.exception ?? false,
        explanation: r.note ?? rule,
        ...(r.memo ? { memo: r.memo } : {}),
      };
    }),
  };
}

const HOW = ['слитно', 'раздельно', 'через дефис'] as const;
type How = (typeof HOW)[number];

/** `'(НЕ)ВЕЖДА|невежда|слитно|!|note|memo'`. */
function spellings(
  task: number,
  id: string,
  title: string,
  rule: string,
  choices: readonly How[],
  lines: readonly string[],
): DictCategory {
  return {
    id,
    title,
    rule,
    kind: 'spelling',
    words: lines.map((line) => {
      const [gap, word, answer, flag, note, memo] = line.split('|') as [
        string,
        string,
        How,
        string,
        string,
        string,
      ];
      return {
        key: `${task}:${id}:${word}`,
        word,
        gap,
        answer,
        options: [...choices],
        exception: flag === '!',
        explanation: note || rule,
        ...(memo ? { memo } : {}),
      };
    }),
  };
}

