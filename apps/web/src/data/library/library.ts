/**
 * The learning-centre library (docs/LIBRARY.md): «Полезные материалы» —
 * reference tables, cheat sheets, algorithms — and «Стратегии» — how to
 * prepare and how to work on the exam day.
 *
 * One manifest, one storage: a library text is a Markdown file in
 * src/content/library/<id>.md, rendered by the same TheoryMarkdown as the
 * theory (formulas, callouts, figures). A list that already exists in
 * the theory (the FIPI stress list, the paronym list) is not copied: the
 * item points at that theory file (`theoryFile`) and the library only
 * gives it a card. Texts load lazily, one chunk per file.
 */

export type LibrarySection = 'materials' | 'strategies';
export type LibrarySubject = 'math' | 'russian' | 'general';

export interface LibraryItem {
  id: string;
  section: LibrarySection;
  subject: LibrarySubject;
  /** A short topic used for grouping and search: «Производная», «Пунктуация». */
  topic: string;
  title: string;
  /** One or two sentences for the card and the search results. */
  description: string;
  /** EGE task numbers the material helps with (for the card's chips). */
  tasks?: readonly number[];
  /** Reuse an existing Russian theory file instead of a library file. */
  theoryFile?: string;
}

export const librarySubjects: readonly { id: LibrarySubject; label: string }[] = [
  { id: 'math', label: 'Математика' },
  { id: 'russian', label: 'Русский язык' },
  { id: 'general', label: 'Общее' },
];

export function subjectLabel(subject: LibrarySubject | 'math' | 'russian'): string {
  return librarySubjects.find((s) => s.id === subject)?.label ?? subject;
}

const M = (
  id: string,
  topic: string,
  title: string,
  description: string,
  tasks?: number[],
): LibraryItem => ({ id, section: 'materials', subject: 'math', topic, title, description, tasks });
const R = (
  id: string,
  topic: string,
  title: string,
  description: string,
  tasks?: number[],
  theoryFile?: string,
): LibraryItem => ({
  id,
  section: 'materials',
  subject: 'russian',
  topic,
  title,
  description,
  tasks,
  ...(theoryFile ? { theoryFile } : {}),
});
const S = (
  id: string,
  subject: LibrarySubject,
  topic: string,
  title: string,
  description: string,
): LibraryItem => ({ id, section: 'strategies', subject, topic, title, description });

